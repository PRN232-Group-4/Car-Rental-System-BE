using System.Runtime.CompilerServices;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using Xunit;

namespace VehicleRental.Tests;

/// <summary>
/// Pins the public HTTP contract: the OpenAPI document the running host serves must match the committed
/// golden file byte for byte, so an accidental route, verb, parameter, schema or response change shows up
/// as a failing test with a diff instead of shipping unnoticed.
/// </summary>
/// <remarks>
/// <para>
/// The host is the one <see cref="CompositionSmokeTests.RealProgramFactory"/> builds, so this test inherits
/// that factory's safety rails — no database, no Redis, no hosted service — and never boots Program.cs
/// against the real appsettings.json.
/// </para>
/// <para>
/// Regenerating is deliberate and can never pass silently: set <c>UPDATE_SWAGGER_SNAPSHOT=1</c>, run the
/// test, and the golden file is rewritten while the test fails, so the regenerated bytes must be reviewed
/// and committed with the change that caused them.
/// </para>
/// </remarks>
public sealed class SwaggerContractTests : IClassFixture<CompositionSmokeTests.RealProgramFactory>
{
    private const string SnapshotVariable = "UPDATE_SWAGGER_SNAPSHOT";
    private const string DocumentPath = "/swagger/v1/swagger.json";
    private const string SnapshotFile = "Contracts/swagger.v1.json";

    private readonly CompositionSmokeTests.RealProgramFactory _factory;

    public SwaggerContractTests(CompositionSmokeTests.RealProgramFactory factory) => _factory = factory;

    [Fact]
    public async Task Swagger_document_matches_the_committed_snapshot()
    {
        using var client = _factory.CreateClient();
        using var response = await client.GetAsync(DocumentPath);
        var actual = await response.Content.ReadAsByteArrayAsync();
        Assert.True(response.IsSuccessStatusCode,
            $"GET {DocumentPath} returned {(int)response.StatusCode}: {Encoding.UTF8.GetString(actual)}");

        var snapshot = SnapshotPath();
        if (Environment.GetEnvironmentVariable(SnapshotVariable) == "1")
        {
            Directory.CreateDirectory(Path.GetDirectoryName(snapshot)!);
            await File.WriteAllBytesAsync(snapshot, actual);
            Assert.Fail($"{SnapshotVariable}=1: rewrote {SnapshotFile} with {actual.Length} bytes (SHA-256 {Hash(actual)}). " +
                        $"Re-run without {SnapshotVariable} and review the diff before committing it.");
        }

        Assert.True(File.Exists(snapshot),
            $"The committed snapshot {SnapshotFile} is missing. Create it deliberately with {SnapshotVariable}=1.");
        var expected = await File.ReadAllBytesAsync(snapshot);

        Assert.True(expected.AsSpan().SequenceEqual(actual), MismatchMessage(expected, actual));
    }

    /// <summary>
    /// The golden file lives next to this test in the source tree, not in the output folder, so a
    /// regeneration edits the file that gets committed.
    /// </summary>
    private static string SnapshotPath([CallerFilePath] string sourceFile = "") =>
        Path.Combine(Path.GetDirectoryName(sourceFile)!, SnapshotFile.Replace('/', Path.DirectorySeparatorChar));

    private static string MismatchMessage(byte[] expected, byte[] actual) => string.Join(Environment.NewLine,
    [
        $"The OpenAPI document no longer matches the committed snapshot {SnapshotFile}.",
        $"Snapshot: {expected.Length} bytes, SHA-256 {Hash(expected)}",
        $"Served  : {actual.Length} bytes, SHA-256 {Hash(actual)}",
        $"First difference: {FirstDifference(expected, actual)}",
        $"If the change is intended, regenerate the snapshot with {SnapshotVariable}=1, review the diff, and commit it " +
        "together with the change that caused it."
    ]);

    /// <summary>Names the first differing JSON path, falling back to the first differing line.</summary>
    private static string FirstDifference(byte[] expected, byte[] actual)
    {
        var expectedText = Encoding.UTF8.GetString(expected).Replace("\r\n", "\n");
        var actualText = Encoding.UTF8.GetString(actual).Replace("\r\n", "\n");

        if (TryReadDocument(expected, actual, out var expectedRoot, out var actualRoot) &&
            FirstJsonPathDifference(expectedRoot, actualRoot, "$") is { } path)
        {
            return $"JSON path {path} (line {FirstDifferingLine(expectedText, actualText)} of the snapshot)";
        }

        if (TryReadDocument(expected, actual, out expectedRoot, out actualRoot) &&
            FirstJsonPathDifference(expectedRoot, actualRoot, "$") is null)
        {
            return $"line {FirstDifferingLine(expectedText, actualText)} — the JSON values are equal, so only the " +
                   "formatting changed";
        }

        return $"line {FirstDifferingLine(expectedText, actualText)}";
    }

    private static bool TryReadDocument(byte[] expected, byte[] actual, out JsonElement expectedRoot, out JsonElement actualRoot)
    {
        expectedRoot = default;
        actualRoot = default;
        try
        {
            using var expectedDocument = JsonDocument.Parse(expected);
            using var actualDocument = JsonDocument.Parse(actual);
            expectedRoot = expectedDocument.RootElement.Clone();
            actualRoot = actualDocument.RootElement.Clone();
            return true;
        }
        catch (JsonException)
        {
            return false;
        }
    }

    private static string? FirstJsonPathDifference(JsonElement expected, JsonElement actual, string path)
    {
        if (expected.ValueKind != actual.ValueKind) return $"{path} (expected {expected.ValueKind}, found {actual.ValueKind})";

        switch (expected.ValueKind)
        {
            case JsonValueKind.Object:
                foreach (var property in expected.EnumerateObject())
                    if (!actual.TryGetProperty(property.Name, out var value))
                        return $"{path}.{property.Name} (missing from the served document)";
                    else if (FirstJsonPathDifference(property.Value, value, $"{path}.{property.Name}") is { } nested)
                        return nested;
                foreach (var property in actual.EnumerateObject())
                    if (!expected.TryGetProperty(property.Name, out _))
                        return $"{path}.{property.Name} (unexpected in the served document)";
                return null;

            case JsonValueKind.Array:
                var expectedItems = expected.EnumerateArray().ToList();
                var actualItems = actual.EnumerateArray().ToList();
                for (var index = 0; index < Math.Min(expectedItems.Count, actualItems.Count); index++)
                    if (FirstJsonPathDifference(expectedItems[index], actualItems[index], $"{path}[{index}]") is { } item)
                        return item;
                return expectedItems.Count == actualItems.Count
                    ? null
                    : $"{path} (expected {expectedItems.Count} items, found {actualItems.Count})";

            default:
                return expected.GetRawText() == actual.GetRawText()
                    ? null
                    : $"{path} (expected {expected.GetRawText()}, found {actual.GetRawText()})";
        }
    }

    private static int FirstDifferingLine(string expected, string actual)
    {
        var expectedLines = expected.Split('\n');
        var actualLines = actual.Split('\n');
        for (var index = 0; index < Math.Min(expectedLines.Length, actualLines.Length); index++)
            if (expectedLines[index] != actualLines[index])
                return index + 1;
        return Math.Min(expectedLines.Length, actualLines.Length) + 1;
    }

    private static string Hash(byte[] bytes) => Convert.ToHexString(SHA256.HashData(bytes)).ToLowerInvariant();
}
