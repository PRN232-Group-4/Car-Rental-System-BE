-- A rental row reserves the requested vehicle/window; the official order is issued only
-- after staff approval and a verified receipt (or approval of a prepaid subscription).
ALTER TABLE invoices ADD COLUMN IF NOT EXISTS payment_method VARCHAR(20) NOT NULL DEFAULT 'payos';
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='ck_invoice_payment_method') THEN
        ALTER TABLE invoices ADD CONSTRAINT ck_invoice_payment_method CHECK (payment_method IN ('payos','cash'));
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS rental_orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id INTEGER NOT NULL UNIQUE,
    payment_id INTEGER UNIQUE,
    amount NUMERIC(18,2) NOT NULL CHECK (amount>=0),
    payment_method VARCHAR(20) NOT NULL CHECK (payment_method IN ('payos','cash','subscription')),
    payment_status VARCHAR(20) NOT NULL DEFAULT 'paid' CHECK (payment_status='paid'),
    confirmed_by VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

-- Preserve only orders supported by both explicit approval and existing paid ledger evidence.
INSERT INTO rental_orders(rental_id,payment_id,amount,payment_method,confirmed_by)
SELECT r.id,p.id,CASE WHEN r.is_subscription THEN 0 ELSE p.amount END,
       CASE WHEN r.is_subscription THEN 'subscription' ELSE p.method END,p.reviewed_by
FROM rentals r
LEFT JOIN LATERAL (
    SELECT p.id,p.amount,p.method,p.reviewed_by FROM invoices i JOIN payments p ON p.invoice_id=i.id
    WHERE i.rental_id=r.id AND i.kind='rental' AND i.status='paid'
      AND p.type='rental' AND p.status='paid' AND p.method IN ('payos','cash')
    ORDER BY p.id LIMIT 1
) p ON true
WHERE r.confirmed_at IS NOT NULL AND r.status<>'cancelled' AND (r.is_subscription OR p.id IS NOT NULL)
ON CONFLICT(rental_id) DO NOTHING;
