-- Phase 2 / rental settlement integrity (D2 decision + single-deduction guarantee).
--
-- 1. invoices.kind learns 'supplementary': overtime that the remaining package hours cannot cover is
--    billed on its own payable invoice instead of being silently dropped by the GREATEST(0, ...) clamp.
-- 2. fn_block_invoice_for_subscription still blocks every cash invoice on a subscription rental, but
--    lets the supplementary kind through (that is the whole point of D2).
-- 3. ux_invoices_rental_supplementary keeps the supplementary invoice idempotent: at most one per rental.
-- 4. subscription_hour_ledger is a per-rental ledger with a UNIQUE rental_id, so package hours can only
--    ever be taken once per rental - a second settlement fails on the index instead of deducting twice.
--
-- Idempotent: every statement is guarded, nothing destructive, safe to re-run.

-- 1. Allow the 'supplementary' invoice kind -------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conname = 'ck_invoices_kind'
       AND conrelid = 'invoices'::regclass
       AND pg_get_constraintdef(oid) LIKE '%supplementary%'
  ) THEN
    ALTER TABLE invoices DROP CONSTRAINT IF EXISTS ck_invoices_kind;
    ALTER TABLE invoices ADD CONSTRAINT ck_invoices_kind
      CHECK (kind IN ('rental','overtime','supplementary'));
  END IF;
END $$;

-- 2. Only the supplementary kind may be raised on a subscription rental ----------------------------
--    'rental' (and every other kind) stays blocked exactly as before.
CREATE OR REPLACE FUNCTION fn_block_invoice_for_subscription()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.kind <> 'supplementary'
       AND EXISTS (SELECT 1 FROM rentals WHERE id = NEW.rental_id AND is_subscription) THEN
        RAISE EXCEPTION 'Rental % là rental theo gói (subscription), không được tạo invoice', NEW.rental_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 3. At most one supplementary invoice per rental --------------------------------------------------
CREATE UNIQUE INDEX IF NOT EXISTS ux_invoices_rental_supplementary
  ON invoices (rental_id) WHERE kind = 'supplementary';

-- 4. Per-rental package hour ledger ----------------------------------------------------------------
--    One row per rental that consumed package hours. hours = hours actually taken out of the package
--    (0 when the package was already exhausted and the excess went to the supplementary invoice).
CREATE TABLE IF NOT EXISTS subscription_hour_ledger (
  id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rental_id                INTEGER NOT NULL REFERENCES rentals(id),
  customer_subscription_id INTEGER NOT NULL REFERENCES customer_subscriptions(id),
  hours                    NUMERIC(10,2) NOT NULL,
  created_at               TIMESTAMP NOT NULL DEFAULT now(),
  CONSTRAINT ck_subscription_hour_ledger_hours CHECK (hours >= 0)
);

-- The invariant that makes double deduction impossible rather than merely absent.
CREATE UNIQUE INDEX IF NOT EXISTS ux_subscription_hour_ledger_rental
  ON subscription_hour_ledger (rental_id);

CREATE INDEX IF NOT EXISTS ix_subscription_hour_ledger_subscription
  ON subscription_hour_ledger (customer_subscription_id, id);

COMMENT ON TABLE subscription_hour_ledger IS
  'Phase 2 D-2: one row per rental, unique on rental_id, written inside the settlement transaction before remaining_hours is adjusted.';
COMMENT ON COLUMN subscription_hour_ledger.hours IS
  'Package hours taken by this rental. 0 means the package was already exhausted; the excess is on a supplementary invoice.';
