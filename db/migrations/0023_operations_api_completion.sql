CREATE TABLE report_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id INTEGER NOT NULL,
    from_status VARCHAR(255),
    to_status VARCHAR(255),
    reason TEXT,
    actor VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE INDEX ix_report_history_report ON report_history(report_id,id);
ALTER TABLE reports ADD COLUMN status_reason TEXT;
ALTER TABLE reports ADD COLUMN status_actor VARCHAR(255);

CREATE FUNCTION fn_report_status_history() RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO report_history(report_id,to_status,actor)
        VALUES(NEW.id,NEW.status,COALESCE(NEW.status_actor,'staff:' || NEW.reporter_staff_id::text));
    ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
        INSERT INTO report_history(report_id,from_status,to_status,reason,actor)
        VALUES(NEW.id,OLD.status,NEW.status,NEW.status_reason,COALESCE(NEW.resolved_by,NEW.status_actor));
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_report_status_history AFTER INSERT OR UPDATE OF status ON reports
FOR EACH ROW EXECUTE FUNCTION fn_report_status_history();

CREATE TABLE rating_moderation_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rating_id INTEGER NOT NULL, status VARCHAR(20) NOT NULL, reason TEXT NOT NULL,
    actor VARCHAR(255) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE OR REPLACE FUNCTION fn_update_staff_rating() RETURNS TRIGGER AS $$
BEGIN
    PERFORM 1 FROM staffs WHERE id=NEW.staff_id FOR UPDATE;
    UPDATE staffs SET rating = (
        SELECT ROUND(AVG(rating)::NUMERIC, 2) FROM staff_ratings
        WHERE staff_id = NEW.staff_id AND status='visible'
    ) WHERE id = NEW.staff_id;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
