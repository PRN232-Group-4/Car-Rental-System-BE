-- Staff ratings: mot rental co the duoc customer danh gia toi da 1 lan
CREATE TABLE staff_ratings (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id           INTEGER NOT NULL REFERENCES rentals(id),
    staff_id            INTEGER NOT NULL REFERENCES staffs(id),
    rating              NUMERIC(3,2) NOT NULL CHECK (rating >= 1 AND rating <= 5),
    comment             TEXT,
    created_at          TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (rental_id, staff_id)
);

CREATE INDEX ix_staff_ratings_staff ON staff_ratings(staff_id);

CREATE OR REPLACE FUNCTION fn_update_staff_rating() RETURNS TRIGGER AS $$
BEGIN
    UPDATE staffs SET rating = (
        SELECT ROUND(AVG(rating)::NUMERIC, 2) FROM staff_ratings WHERE staff_id = NEW.staff_id
    ) WHERE id = NEW.staff_id;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_update_staff_rating
AFTER INSERT OR UPDATE ON staff_ratings
FOR EACH ROW EXECUTE FUNCTION fn_update_staff_rating();