-- 1. Tracking Devices: thiết bị GPS gắn trên xe để gửi dữ liệu tọa độ
CREATE TABLE IF NOT EXISTS tracking_devices (
    id              VARCHAR(64) PRIMARY KEY,
    vehicle_id      INTEGER NOT NULL,
    key_hash        VARCHAR(255) NOT NULL,
    name            VARCHAR(255),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    last_ping_at    TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_tracking_devices_vehicle_id ON tracking_devices (vehicle_id);

-- 2. Vehicle Positions: lịch sử vị trí / telemetry định kỳ từ thiết bị GPS
CREATE TABLE IF NOT EXISTS vehicle_positions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id      INTEGER NOT NULL,
    device_id       VARCHAR(64) NOT NULL,
    latitude        NUMERIC(10, 7) NOT NULL,
    longitude       NUMERIC(10, 7) NOT NULL,
    speed_kmh       NUMERIC(5, 2),
    heading         NUMERIC(5, 2),
    accuracy_m      NUMERIC(6, 2),
    recorded_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_vehicle_positions_vehicle_time ON vehicle_positions (vehicle_id, recorded_at DESC);
CREATE INDEX IF NOT EXISTS ix_vehicle_positions_recorded_at ON vehicle_positions (recorded_at);

-- 3. Vehicle Last Positions: lưu nhanh vị trí hiện tại/mới nhất của từng xe
CREATE TABLE IF NOT EXISTS vehicle_last_positions (
    vehicle_id      INTEGER PRIMARY KEY,
    device_id       VARCHAR(64) NOT NULL,
    latitude        NUMERIC(10, 7) NOT NULL,
    longitude       NUMERIC(10, 7) NOT NULL,
    speed_kmh       NUMERIC(5, 2),
    heading         NUMERIC(5, 2),
    accuracy_m      NUMERIC(6, 2),
    address         VARCHAR(500),
    recorded_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_vehicle_last_positions_coords ON vehicle_last_positions (latitude, longitude);

-- 4. Geofences: các vùng địa lý (vùng cho phép, vùng cấm, bãi xe/trạm)
CREATE TABLE IF NOT EXISTS geofences (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255) NOT NULL,
    zone_type       VARCHAR(50) NOT NULL DEFAULT 'allowed', -- 'allowed', 'prohibited', 'facility'
    center_lat      NUMERIC(10, 7) NOT NULL,
    center_lng      NUMERIC(10, 7) NOT NULL,
    radius_meters   NUMERIC(10, 2) NOT NULL,
    polygon_geojson TEXT,
    facility_id     INTEGER,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

-- 5. Geofence Events: ghi nhận sự kiện xe vào/rời khu vực
CREATE TABLE IF NOT EXISTS geofence_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id      INTEGER NOT NULL,
    rental_id       INTEGER,
    geofence_id     INTEGER NOT NULL,
    event_type      VARCHAR(20) NOT NULL, -- 'ENTER', 'EXIT'
    latitude        NUMERIC(10, 7) NOT NULL,
    longitude       NUMERIC(10, 7) NOT NULL,
    occurred_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_geofence_events_vehicle ON geofence_events (vehicle_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS ix_geofence_events_rental ON geofence_events (rental_id, occurred_at DESC);

-- 6. Tracking Alerts: cảnh báo xe đi lệch lộ trình, trả sai điểm, vi phạm vùng
CREATE TABLE IF NOT EXISTS tracking_alerts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id           INTEGER,
    vehicle_id          INTEGER NOT NULL,
    alert_type          VARCHAR(50) NOT NULL, -- 'route_deviation', 'wrong_return_point', 'geofence_violation', 'speeding'
    severity            VARCHAR(20) NOT NULL DEFAULT 'warning', -- 'info', 'warning', 'critical'
    message             VARCHAR(500) NOT NULL,
    latitude            NUMERIC(10, 7) NOT NULL,
    longitude           NUMERIC(10, 7) NOT NULL,
    expected_latitude   NUMERIC(10, 7),
    expected_longitude  NUMERIC(10, 7),
    distance_meters     NUMERIC(10, 2),
    is_resolved         BOOLEAN NOT NULL DEFAULT FALSE,
    resolved_at         TIMESTAMP WITH TIME ZONE,
    resolved_by         VARCHAR(255),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_tracking_alerts_rental ON tracking_alerts (rental_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_tracking_alerts_vehicle ON tracking_alerts (vehicle_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_tracking_alerts_unresolved ON tracking_alerts (is_resolved) WHERE is_resolved = FALSE;
