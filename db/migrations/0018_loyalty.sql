CREATE OR REPLACE FUNCTION fn_immutable_row() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Bản ghi không được phép chỉnh sửa hoặc xóa' USING ERRCODE = '23505';
END $$;

CREATE TABLE IF NOT EXISTS customer_loyalty_transactions (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id     INTEGER NOT NULL,
  rental_id       INTEGER,
  type            VARCHAR(10) NOT NULL,
  points          INTEGER NOT NULL,
  reason          VARCHAR(255) NOT NULL,
  ref_type        VARCHAR(30),
  ref_id          BIGINT,
  idempotency_key VARCHAR(64),
  balance_after   INTEGER NOT NULL DEFAULT 0,
  created_by      VARCHAR(255),
  created_at      TIMESTAMP NOT NULL DEFAULT now(),
  CONSTRAINT ck_clt_type CHECK (type IN ('earn','redeem','reverse','adjust')),
  CONSTRAINT ck_clt_points CHECK (
       (type = 'earn'   AND points > 0)
    OR (type = 'redeem' AND points < 0)
    OR (type IN ('reverse','adjust') AND points <> 0))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_clt_ref ON customer_loyalty_transactions (type, ref_type, ref_id)
  WHERE ref_type IS NOT NULL AND type IN ('earn','redeem','reverse');

CREATE UNIQUE INDEX IF NOT EXISTS ux_clt_idem ON customer_loyalty_transactions (customer_id, idempotency_key)
  WHERE idempotency_key IS NOT NULL;

CREATE INDEX IF NOT EXISTS ix_clt_customer ON customer_loyalty_transactions (customer_id, id DESC);

-- BEFORE: chỉ KHÓA + kiểm tra + tính balance_after (KHÔNG ghi bảng khác)
CREATE OR REPLACE FUNCTION fn_loyalty_before_insert() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE cur INTEGER;
BEGIN
  SELECT loyalty_point INTO cur FROM customers WHERE id = NEW.customer_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Customer % không tồn tại', NEW.customer_id; END IF;
  IF cur + NEW.points < 0 THEN
    RAISE EXCEPTION 'Số dư điểm không đủ (%/%)', cur, NEW.points USING ERRCODE = '23514';
  END IF;
  NEW.balance_after := cur + NEW.points;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_clt_before_insert ON customer_loyalty_transactions;
CREATE TRIGGER trg_clt_before_insert BEFORE INSERT ON customer_loyalty_transactions
  FOR EACH ROW EXECUTE FUNCTION fn_loyalty_before_insert();

-- AFTER: cập nhật số dư đệm (chỉ chạy khi dòng THỰC SỰ được chèn)
CREATE OR REPLACE FUNCTION fn_loyalty_after_insert() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE customers SET loyalty_point = NEW.balance_after WHERE id = NEW.customer_id;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_clt_after_insert ON customer_loyalty_transactions;
CREATE TRIGGER trg_clt_after_insert AFTER INSERT ON customer_loyalty_transactions
  FOR EACH ROW EXECUTE FUNCTION fn_loyalty_after_insert();

-- Bất biến: cấm UPDATE / DELETE / TRUNCATE
DROP TRIGGER IF EXISTS trg_clt_immutable ON customer_loyalty_transactions;
CREATE TRIGGER trg_clt_immutable BEFORE UPDATE OR DELETE ON customer_loyalty_transactions
  FOR EACH ROW EXECUTE FUNCTION fn_immutable_row();

DROP TRIGGER IF EXISTS trg_clt_no_truncate ON customer_loyalty_transactions;
CREATE TRIGGER trg_clt_no_truncate BEFORE TRUNCATE ON customer_loyalty_transactions
  FOR EACH STATEMENT EXECUTE FUNCTION fn_immutable_row();

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'ck_customers_loyalty_nonneg'
  ) THEN
    ALTER TABLE customers ADD CONSTRAINT ck_customers_loyalty_nonneg CHECK (loyalty_point >= 0);
  END IF;
END $$;

CREATE OR REPLACE VIEW v_loyalty_reconciliation AS
SELECT c.id AS customer_id, c.loyalty_point AS cached,
       COALESCE(SUM(t.points), 0)::INTEGER AS ledger_sum,
       c.loyalty_point - COALESCE(SUM(t.points), 0)::INTEGER AS drift
  FROM customers c LEFT JOIN customer_loyalty_transactions t ON t.customer_id = c.id
 GROUP BY c.id, c.loyalty_point;

