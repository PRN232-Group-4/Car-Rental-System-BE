-- =========================================================
-- Vehicle Rental System - PostgreSQL DDL v2 (no foreign keys)
-- Based on the conceptual ERD
-- =========================================================
-- Các cột "xxx_id" bên dưới là khóa ngoại về mặt logic, comment ở cuối dòng cho biết trỏ tới bảng nào.

-- =========================================================
-- 1. Users / Organization
-- =========================================================
CREATE TABLE users (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255) NOT NULL,
    fullname        VARCHAR(255),
    gender          VARCHAR(255),
    password_hash   VARCHAR(255),
    avatar          VARCHAR(255),
    phone           VARCHAR(255),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_users_email ON users (email);

CREATE TABLE roles (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(255) NOT NULL
);

-- Idempotent baseline roles used by policy authorization.
INSERT INTO roles (name)
SELECT role_name FROM (VALUES ('Customer'), ('Staff'), ('Admin'), ('Driver'), ('Maintenance')) AS seed(role_name)
WHERE NOT EXISTS (SELECT 1 FROM roles WHERE roles.name = seed.role_name);

CREATE TABLE user_roles (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER NOT NULL,   -- -> users.id
    role_id     INTEGER NOT NULL    -- -> roles.id
);

CREATE TABLE departments (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(255) NOT NULL
);

CREATE TABLE facilities (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    address     VARCHAR(255)
);

-- Users "is a" Staff (1-1)
-- Staff cũng đóng vai trò tài xế (gộp bảng drivers cũ vào đây)
CREATE TABLE staffs (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             INTEGER NOT NULL,   -- -> users.id (unique)
    department_id       INTEGER,            -- -> departments.id  ("has")
    facility_id         INTEGER,            -- -> facilities.id   ("works at")
    hired_date          DATE,
    is_driver           BOOLEAN NOT NULL DEFAULT FALSE,
    license_number      VARCHAR(255),
    license_type        VARCHAR(255),
    license_issue_date  DATE,
    license_expiry_date DATE,
    license_img         VARCHAR(255),
    rating              NUMERIC(3,2)
);
CREATE UNIQUE INDEX ux_staffs_user ON staffs (user_id);

-- Users "is a" Customer (1-0..1)
CREATE TABLE customers (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             INTEGER NOT NULL,   -- -> users.id (unique)
    license_number      VARCHAR(255),
    license_type        VARCHAR(255),
    license_issue_date  DATE,
    license_expiry_date DATE,
    license_img         VARCHAR(255),
    license_status      VARCHAR(20) NOT NULL DEFAULT 'pending',
    loyalty_point       INTEGER NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX ux_customers_user ON customers (user_id);

-- =========================================================
-- 2. Vehicles
-- =========================================================
