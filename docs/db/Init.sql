CREATE TABLE longterm_rental_contract (
    rental_id               INTEGER PRIMARY KEY,    -- -> rentals.id
    start_time              TIMESTAMP,
    end_time                TIMESTAMP,
    monthly_price_snapshot  NUMERIC(14,2),
    contract_link           VARCHAR(255),
    signed_at               TIMESTAMP,
    pick_up_location        VARCHAR(255),
    pick_up_method          VARCHAR(255),
    staff_pick_up_id        INTEGER                 -- -> staffs.id
);

-- Rental "has assignments" / Staff "assigned driver" / Vehicle Assignment "uses vehicle"
CREATE TABLE vehicle_assignments (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id         INTEGER NOT NULL,     -- -> rentals.id
    vehicle_id        INTEGER NOT NULL,     -- -> vehicles.id
    driver_staff_id   INTEGER,              -- -> staffs.id (NULL nếu khách tự lái)
    status            VARCHAR(255),
    assigned_at       TIMESTAMP NOT NULL DEFAULT now()
);

-- =========================================================
-- 6. Inspection: kiểm tra xe TRƯỚC và SAU mỗi lần thuê
-- =========================================================
CREATE TABLE inspections (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id         INTEGER NOT NULL,     -- -> rentals.id ("has inspections")
    vehicle_id        INTEGER NOT NULL,     -- -> vehicles.id
    staff_id          INTEGER,              -- -> staffs.id (người kiểm tra)
    inspection_type   VARCHAR(20) NOT NULL, -- 'pre_rental' | 'post_rental'
    is_ok             BOOLEAN,              -- xe có ổn không
    odometer_km       NUMERIC(10,1),
    fuel_battery_level NUMERIC(5,2),        -- % xăng / pin
    damage_notes      VARCHAR(500),
    img_urls          TEXT,
    inspected_at      TIMESTAMP,
    created_at        TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT ck_inspection_type CHECK (inspection_type IN ('pre_rental', 'post_rental'))
);
-- Mỗi rental chỉ có tối đa 1 lần kiểm tra trước và 1 lần kiểm tra sau
CREATE UNIQUE INDEX ux_inspection_rental_type ON inspections (rental_id, inspection_type);

-- =========================================================
-- 7. Invoice & Payments
-- =========================================================
-- Chỉ dành cho thuê trực tiếp (xem trigger bên dưới)
CREATE TABLE invoices (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id       INTEGER NOT NULL,       -- -> rentals.id ("invoices")
    invoice_number  VARCHAR(50) NOT NULL,
    amount          NUMERIC(14,2) NOT NULL,
    vat_amount      NUMERIC(14,2) NOT NULL DEFAULT 0,
    status          VARCHAR(255) NOT NULL DEFAULT 'unpaid',
    issued_at       TIMESTAMP NOT NULL DEFAULT now(),
    due_at          TIMESTAMP
);
CREATE UNIQUE INDEX ux_invoices_number ON invoices (invoice_number);

-- Thuê trực tiếp : invoice_id có giá trị, is_subscription_payment = FALSE ("has payments")
-- Thuê theo gói  : invoice_id NULL, is_subscription_payment = TRUE ("paid by" rental)
CREATE TABLE payments (
    id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id                INTEGER NOT NULL,   -- -> rentals.id
    invoice_id               INTEGER,            -- -> invoices.id
    customer_id              INTEGER NOT NULL,   -- -> customers.id
    is_subscription_payment  BOOLEAN NOT NULL DEFAULT FALSE,
    amount                   NUMERIC(14,2) NOT NULL,
    status                   VARCHAR(255) NOT NULL,
    type                     VARCHAR(255),       -- deposit / rental / overtime / refund ...
    method                   VARCHAR(255),
    provider_reference       VARCHAR(255),
    paid_at                  TIMESTAMP,
    reviewed_by              VARCHAR(255),       -- audit: ai duyệt yêu cầu hoàn tiền
    reviewed_at              TIMESTAMP,
    created_at               TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT ck_payments_invoice_rule CHECK (
        (is_subscription_payment AND invoice_id IS NULL)
        OR (NOT is_subscription_payment AND invoice_id IS NOT NULL)
    )
);
CREATE UNIQUE INDEX ux_payments_provider_reference ON payments (provider_reference) WHERE provider_reference IS NOT NULL;

