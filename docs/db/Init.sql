CREATE TABLE customer_subscriptions (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      INTEGER NOT NULL,      -- -> customers.id  ("has subscription")
    plan_id          INTEGER NOT NULL,      -- -> subscription_plans.id ("is subscribed to")
