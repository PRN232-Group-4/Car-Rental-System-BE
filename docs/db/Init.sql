-- =========================================================
-- 9. Trigger: đảm bảo quy tắc Subscription vs Thuê trực tiếp
--    (CHECK không tham chiếu được bảng khác nên dùng trigger, không cần FK)
-- =========================================================
CREATE OR REPLACE FUNCTION fn_block_invoice_for_subscription()
RETURNS TRIGGER AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM rentals WHERE id = NEW.rental_id AND is_subscription) THEN
        RAISE EXCEPTION 'Rental % là rental theo gói (subscription), không được tạo invoice', NEW.rental_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_invoice_no_subscription
    BEFORE INSERT OR UPDATE OF rental_id ON invoices
    FOR EACH ROW EXECUTE FUNCTION fn_block_invoice_for_subscription();

CREATE OR REPLACE FUNCTION fn_check_payment_matches_rental()
RETURNS TRIGGER AS $$
DECLARE
    v_is_sub BOOLEAN;
BEGIN
    SELECT is_subscription INTO v_is_sub FROM rentals WHERE id = NEW.rental_id;
    IF v_is_sub IS NULL THEN
        RAISE EXCEPTION 'Rental % không tồn tại', NEW.rental_id;
    END IF;
    IF v_is_sub <> NEW.is_subscription_payment THEN
        RAISE EXCEPTION 'is_subscription_payment không khớp với rental %', NEW.rental_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_payment_match_rental
    BEFORE INSERT OR UPDATE OF rental_id, is_subscription_payment ON payments
    FOR EACH ROW EXECUTE FUNCTION fn_check_payment_matches_rental();
