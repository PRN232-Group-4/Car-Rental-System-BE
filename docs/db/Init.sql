    start_date       DATE NOT NULL,
    end_date         DATE NOT NULL,
    remaining_hours  NUMERIC(10,2),         -- còn lại của package limit
    created_at       TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT ck_cs_dates CHECK (end_date >= start_date)
);

-- =========================================================
-- 5. Rentals
-- =========================================================
-- Thuê trực tiếp : is_subscription = FALSE, customer_subscription_id IS NULL -> có Invoice -> Payment qua Invoice
-- Thuê theo gói  : is_subscription = TRUE,  customer_subscription_id có giá trị -> KHÔNG có Invoice, Payment trực tiếp theo rental
CREATE TABLE rentals (
    id                        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id               INTEGER NOT NULL,   -- -> customers.id ("places")
    vehicle_id                INTEGER NOT NULL,   -- -> vehicles.id
    policy_id                 INTEGER,            -- -> rental_policies.id ("applies to")
    customer_subscription_id  INTEGER,            -- -> customer_subscriptions.id ("uses package limit")
    is_subscription           BOOLEAN NOT NULL DEFAULT FALSE,
    rental_type               VARCHAR(20) NOT NULL,   -- 'hourly' | 'longterm'
    status                    VARCHAR(255) NOT NULL,  -- pending / pre_inspection / renting / post_inspection / completed / cancelled
    vat_price                 NUMERIC(14,2) NOT NULL DEFAULT 0,
    deposit_price             NUMERIC(14,2) NOT NULL DEFAULT 0,
    overtime_price            NUMERIC(14,2) NOT NULL DEFAULT 0,
    total_price               NUMERIC(14,2) NOT NULL DEFAULT 0,
    created_at                TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT ck_rentals_type CHECK (rental_type IN ('hourly', 'longterm')),
    CONSTRAINT ck_rentals_subscription
        CHECK (is_subscription = (customer_subscription_id IS NOT NULL))
);

